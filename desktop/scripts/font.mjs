/** Metin genişliği (piksel). */
export const textWidth = (text, px = 1) => text.length * 4 * px - px;

/** Bilinmeyen karakter boşluk olarak çizilir. */
export function drawText(img, text, x, y, px, rgba) {
  let cx = x;
  for (const ch of text.toLowerCase()) {
    const g = GLYPHS[ch] ?? GLYPHS[" "];
    g.forEach((row, j) =>
      [...row].forEach((bit, i) => {
        if (bit === "1") img.fillRect(cx + i * px, y + j * px, px, px, rgba);
      }),
    );
    cx += 4 * px;
  }
}
